import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import api from '../api/client';

const difficultyOptions = [
  { value: 'easy', label: 'Easy' },
  { value: 'medium', label: 'Medium' },
  { value: 'hard', label: 'Hard' },
];

function HomePage() {
  const navigate = useNavigate();
  const [premise, setPremise] = useState('');
  const [difficulty, setDifficulty] = useState('easy');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleSubmit = async (event) => {
    event.preventDefault();
    const trimmedPremise = premise.trim();

    if (trimmedPremise.length < 20) {
      setError('Your premise must be at least 20 characters long.');
      return;
    }

    setLoading(true);
    setError('');

    try {
      const response = await api.post('/cases/generate', { premise: trimmedPremise, difficulty });
      const createdCase = response.data.case;
      navigate(`/cases/${createdCase.id}`);
    } catch (requestError) {
      setError(requestError?.response?.data?.message || 'Unable to generate a mystery right now.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="page-shell">
      <div className="card">
        <p className="eyebrow">AI Mystery Room</p>
        <h1>Create a Mystery</h1>
        <p className="lead">
          Turn a short story idea into a fictional detective case generated by the server.
        </p>

        <form onSubmit={handleSubmit} className="stack">
          <label className="field">
            <span>Premise</span>
            <textarea
              value={premise}
              onChange={(event) => setPremise(event.target.value)}
              placeholder="A famed collector disappears during a thunderstorm, and the only clue is a locked ledger with three strange names."
              rows={6}
              minLength={20}
              maxLength={1000}
            />
          </label>

          <div className="field">
            <span>Difficulty</span>
            <div className="segment-row">
              {difficultyOptions.map((option) => (
                <button
                  key={option.value}
                  type="button"
                  className={option.value === difficulty ? 'segment active' : 'segment'}
                  onClick={() => setDifficulty(option.value)}
                >
                  {option.label}
                </button>
              ))}
            </div>
          </div>

          {error ? <div className="alert error">{error}</div> : null}

          <button type="submit" disabled={loading} className="primary-button">
            {loading ? 'Generating your case…' : 'Create Mystery'}
          </button>
        </form>
      </div>
    </div>
  );
}

export default HomePage;
